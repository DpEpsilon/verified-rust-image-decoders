#!/usr/bin/env python3
"""Generate complete-observation Verus witnesses from independent oracle indices.

Success positions below are the sums of the code widths in these twelve fixed
streams (m=1 StopAtRaster returns before EOI); error positions are in the JSON.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
records = json.loads((root / 'tests/witnesses.json').read_text())
success_pos = {'one_literal': 9, 'two_literals': 12, 'kwkwk': 12,
               'width_change': 20, 'm1_one_pixel': 4, 'm8_one_literal': 27}
text = '''//! GENERATED by tools/emit_witness_rs.py: complete observations for twelve streams.
use vstd::prelude::*;
verus! {
#[cfg(verus_only)]
use crate::model::{ML, observation, ErrK};
#[cfg(verus_only)]
use crate::lzw::{strict_params, recommended_beta_params};
pub proof fn w_params_distinct()
    ensures strict_params().m_hi == 8, recommended_beta_params().m_hi == 11,
        !strict_params().stop_at_raster, recommended_beta_params().stop_at_raster,
{}
'''
for r in records:
    seq = lambda xs: 'seq![' + ', '.join(f'{v}u8' for v in xs) + ']'
    ps = 'recommended_beta_params()' if r['m'] == 1 else 'strict_params()'
    call = f"ML({r['m']}, {seq(r['data'])}, {r['a']}, {ps})"
    error = f"Some(ErrK::{r['error']})" if r['error'] else 'None'
    pos = r['pos'] if r['error'] else success_pos[r['name']]
    expected = f"observation({seq(r['expected'])}, {error}, {pos}, false)"
    text += f"pub proof fn w_{r['name']}()\n    ensures {call} == {expected},\n{{\n    assert({call} == {expected}) by (compute);\n}}\n"
text += '} // verus!\n'
(root / 'src/witnesses.rs').write_text(text)
print('Generated twelve complete-observation witnesses.')
