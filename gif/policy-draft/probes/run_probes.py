#!/usr/bin/env python3
"""Run the incumbent GIF decoders on the spec-draft vectors plus targeted probes.

Runners come from ~/projects/leniency/gif (build with its build.sh; binaries in
/tmp/claude-0/leniency-gifpng-bin) and ~/projects/leniency/shared/gdk.c (binary
/tmp/claude-0/leniency-target/gdk-formats, mode `file` = gdk_pixbuf_new_from_file).
Writes probes/results.json (durable) and prints a one-line summary per input.

Usage: python3 -I run_probes.py [--only NAME_SUBSTRING]
"""
import hashlib
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
GIF = HERE.parent.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(GIF / 'spec-draft'))
sys.path.insert(0, str(Path.home() / 'projects/leniency'))
import engine  # noqa: E402
import gen_vectors as G  # noqa: E402
import gif_oracle as O  # noqa: E402
from probes_def import PROBES  # noqa: E402

BIN = Path('/tmp/claude-0/leniency-gifpng-bin')
RUNNERS = {
    'glycin': (BIN / 'rust', ['gif:glycin']),
    'image': (BIN / 'rust', ['gif:image']),
    'gdk-anim': (BIN / 'gdk-anim', ['gif', 'anim']),
    'gdk-loader': (BIN / 'gdk-anim', ['gif', 'forced-whole']),
    'gdk-loader-byte': (BIN / 'gdk-anim', ['gif', 'forced-byte']),
    'gdk-file': (Path('/tmp/claude-0/leniency-target/gdk-formats'), ['gif', 'file']),
    'giflib': (BIN / 'gif-native', ['giflib']),
    'libnsgif': (BIN / 'gif-native', ['libnsgif']),
}
WORK = Path('/tmp/claude-0/gif-probes')


def oracle_summary(b):
    s = O.decode_still(b)
    f = O.decode_frames(b)
    out = {'still': s['error'] if 'error' in s else 'ok:' + hashlib.sha256(s['rgba']).hexdigest()}
    if 'error' in f:
        out['frames'] = {'error': f['error']}
    else:
        fr = f['frames']
        seq = hashlib.sha256(b''.join(x['rgba'] for x in fr[:64])).hexdigest()
        out['frames'] = {'n': len(fr), 'seq': seq, 'end': f['end'], 'loop': f['loop_count'],
                         'delays_cs': [x['delay_cs'] for x in fr[:16]],
                         'first': hashlib.sha256(fr[0]['rgba']).hexdigest() if fr else None}
    return out


def inputs():
    seen = {}
    for v in json.loads((GIF / 'spec-draft/VECTORS.json').read_text()):
        if 'pad_to' in v or 'repeat' in v:
            continue
        b = bytes.fromhex(v['input_hex'])
        seen.setdefault(b, ('vec:' + v['name'].split('/')[0], ''))
    for name, b, why in PROBES:
        seen[b] = ('probe:' + name, why)
    wit = Path.home() / 'projects/leniency/gif/witnesses'
    for f in sorted(wit.glob('*.gif')):                 # held out: generated by the leniency harness, not tuned on
        seen.setdefault(f.read_bytes(), ('wit:' + f.stem, 'leniency-harness witness'))
    return [(n, b, why) for b, (n, why) in seen.items()]


def run_one(item):
    name, b, why = item
    p = WORK / (name.replace('/', '_').replace(':', '_') + '.gif')
    p.write_bytes(b)
    res = {}
    for r, spec in RUNNERS.items():
        o = engine.invoke(p, spec, 20)
        keep = {k: o[k] for k in ('status', 'error_class', 'message', 'width', 'height', 'frames', 'rgba_sha256',
                                  'seq_sha256', 'frame_info', 'tail_error', 'loop_period') if k in o}
        if 'message' in keep:
            keep['message'] = str(keep['message'])[:120]
        res[r] = keep
    return {'name': name, 'why': why, 'hex': b.hex() if len(b) <= 4096 else None, 'len': len(b),
            'oracle': oracle_summary(b), 'runners': res}


def main():
    only = sys.argv[sys.argv.index('--only') + 1] if '--only' in sys.argv else None
    WORK.mkdir(parents=True, exist_ok=True)
    items = [i for i in inputs() if not only or only in i[0]]
    with ThreadPoolExecutor(3) as ex:
        results = list(ex.map(run_one, items))
    out = HERE / ('results.json' if not only else 'results-partial.json')
    out.write_text(json.dumps(results, indent=1) + '\n')
    for r in results:
        o = r['oracle']['still']
        cells = []
        for k, v in r['runners'].items():
            if v['status'] != 'ok':
                cells.append(f"{k}=✗{v.get('error_class', v['status'])[:14]}")
            else:
                same = ('ok:' + v['rgba_sha256']) == o
                cells.append(f"{k}={v['width']}x{v['height']}{'=' if same else '≠'}{v['rgba_sha256'][:6]}/{v.get('frames')}")
        print(r['name'], '| strict', o[:12], '|', ' '.join(cells))


if __name__ == '__main__':
    main()
