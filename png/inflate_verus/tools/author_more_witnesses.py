#!/usr/bin/env python3
"""Transcribe input bytes only; symbol traces and expected effects are authored here.

No inflate decoder or oracle supplies expectations. See frozen gen_vectors.py
lines 482-488 and 508-544 for the intended fixed symbols.
"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
V = {v['name']: v for v in json.loads((ROOT.parent/'spec-frozen/VECTORS.json').read_text())}

def wire(name):
    b = bytes.fromhex(V[name]['input_hex']); p = 8; z = b''
    while p + 12 <= len(b):
        n = int.from_bytes(b[p:p+4], 'big')
        if b[p+4:p+8] == b'IDAT': z += b[p+8:p+8+n]
        p += n+12
    return z

def seq(values):
    return 'Seq::<u8>::empty()' if not values else 'seq![' + ', '.join(str(x) + ('u8' if i == 0 else '') for i,x in enumerate(values)) + ']'

def symbol(s):
    return (s+48,8) if s<144 else (s+256,9) if s<256 else (s-256,7) if s<280 else (s-88,8)

# Each row: frozen name, image R, decoded symbols at authored bit positions,
# stream-order output prefixes, terminal status, terminal bit position.
CASES = [
 ('deflate/fixed-lit-286',4,[(19,286)],[], 'InvalidSymbol',27),
 ('deflate/distance-before-output',4,[(19,257)],[], 'DistanceTooFar',31),
 ('deflate/distance-beyond-output',4,[(19,0),(27,257)],[0], 'DistanceTooFar',39),
 ('deflate/fixed-dist-30',4,[(19,0),(27,257)],[0], 'InvalidSymbol',39),
 ('deflate/fixed-dist-31',4,[(19,0),(27,257)],[0], 'InvalidSymbol',39),
 ('deflate/fixed-dist-30-then-eof',4,[(19,0),(27,257)],[0], 'InvalidSymbol',39),
 ('deflate/fixed-dist-31-then-eof',4,[(19,0),(27,257)],[0], 'InvalidSymbol',39),
 ('deflate/distance-equals-output',5,[(19,0),(27,7),(35,257),(47,256)],[0,7,0,7,0], 'Done',54),
 ('deflate/match-overruns-image-is-excess',4,[(19,0),(27,7),(35,257)],[0,7,0,7], 'Full',47),
]
lines = ['//! Authored fixed-block model/public-entry witnesses. Generated by tools/author_more_witnesses.py.',
 'use crate::{model as m, InflateOptions, Status, InflateError as E};',
 'use crate::witnesses::{wire_word, fixed_decode, fixed_dist_decode, check_at};',
 'use vstd::prelude::*;', 'verus! {']
for name,L,trace,raw,status,end in CASES:
    z = wire(name); zs=seq(z); rs=seq(raw)
    fname=name.replace('/','_').replace('-','_')
    lines += [f'/// {name}: authored symbol trace, R={L}.', '#[verifier::spinoff_prover]', f'fn {fname}() {{',
      '    hide(m::MDec); hide(m::decode_prefix); hide(m::cw);',
      '    hide(m::MCompressedStep); hide(m::MCompressed);',
      f'    let wire = [{", ".join(hex(x)+( "u8" if i==0 else "") for i,x in enumerate(z))}];',
      '    proof {', f'        let z = {zs};',
      '        assert(crate::limits::WINDOW_MAX == 32768) by (compute);',
      '        assert(m::pow2(15) == 32768) by (compute);']
    for start,s in trace:
        code,n=symbol(s)
        lines += [f'        assert(wire_word({zs}, {start}, {n}) == m::msb_bits({code}, {n})) by (compute);',
                  f'        fixed_decode(z, {start}, {s});']
    ds = None
    if 'distance-before' in name: dp,ds=26,0
    elif 'distance-beyond' in name: dp,ds=34,1
    elif 'fixed-dist-' in name: dp,ds=34,30 if '-30' in name else 31
    elif 'distance-equals' in name or 'match-overruns' in name: dp,ds=42,1
    if ds is not None:
        lines += [f'        assert(wire_word({zs}, {dp}, 5) == m::msb_bits({ds}, 5)) by (compute);',
                  f'        fixed_dist_decode(z, {dp}, {ds});']
    # Explicit literal transitions followed by one terminal match/symbol.
    prefix=[]
    for start,s in trace:
        if s>=256: break
        nxt=prefix+[s]
        lines += [f'        assert({seq(prefix)}.push({s}) =~= {seq(nxt)});',
          f'        assert(m::MCompressedStep(z, {start}, {seq(prefix)}, {L}, 32768, m::fixed_lit_lengths(), m::fixed_dist_lengths())',
          f'            == (m::SymbolEffect::Next {{ out: {seq(nxt)}, position: {start+symbol(s)[1]} }})) by {{ reveal(m::MCompressedStep); }}']
        prefix=nxt
    start,s=next((p,s) for p,s in trace if s>=256)
    if s==257:
        out_effect = f'm::OutputEffect::Next {{ out: {rs} }}' if status=='Done' else f'm::OutputEffect::Full {{ out: {rs} }}' if status=='Full' else f'm::OutputEffect::Error {{ error: m::InflateFault::{status}, out: {rs} }}'
        if ds<30:
            distance=ds+1
            lines += [f'        assert(m::MCopy({seq(prefix)}, {L}, 32768, {distance}, 3) == ({out_effect})) by (compute);']
    term = f'm::SymbolEffect::Next {{ out: {rs}, position: {end-7} }}' if status=='Done' else f'm::SymbolEffect::Full {{ out: {rs} }}' if status=='Full' else f'm::SymbolEffect::Error {{ error: m::InflateFault::{status}, out: {rs}, position: {end} }}'
    lines += [f'        assert(m::MCompressedStep(z, {start}, {seq(prefix)}, {L}, 32768, m::fixed_lit_lengths(), m::fixed_dist_lengths())',
              f'            == ({term})) by {{ reveal(m::MCompressedStep); }}']
    if status=='Done':
        lines += [f'        assert(m::MCompressedStep(z, {end-7}, {rs}, {L}, 32768, m::fixed_lit_lengths(), m::fixed_dist_lengths())',
                  f'            == (m::SymbolEffect::End {{ out: {rs}, position: {end} }})) by {{ reveal(m::MCompressedStep); }}']
    effect = f'm::StoredEffect::End {{ out: {rs}, position: {end} }}' if status=='Done' else f'm::StoredEffect::Full {{ out: {rs} }}' if status=='Full' else f'm::StoredEffect::Error {{ error: m::InflateFault::{status}, out: {rs}, position: {end} }}'
    lines += [f'        assert(m::MCompressed(z, 19, Seq::empty(), {L}, 32768, m::fixed_lit_lengths(), m::fixed_dist_lengths())',
              f'            == ({effect})) by {{ reveal_with_fuel(m::MCompressed, 5); }}',
              f'        assert(m::field_value({zs}, 16, 1) == 1) by (compute);',
              f'        assert(m::field_value({zs}, 17, 2) == 1) by (compute);',
              f'        assert(m::MOneBlock(z, 16, Seq::empty(), {L}, 32768, true) == (true, {effect}));',
              f'        assert(m::MBlk(z, 16, Seq::empty(), {L}, 32768, true) == ({effect}));']
    if status=='Done':
        lines += [f'        assert(m::MFinish({zs}, {end}, {rs}, {L}, false)',
                  f'            == (m::StoredEffect::End {{ out: {rs}, position: {8*len(z)} }})) by (compute);']
    modelstatus = f'm::InflateStatus::{status}' if status in ('Done','Full') else f'm::InflateStatus::Error(m::InflateFault::{status})'
    execstatus = f'Status::{status}' if status in ('Done','Full') else f'Status::Err(E::{status})'
    lines += [f'        assert(m::Inflate(z, {L}, true, false).status == {modelstatus});',
              f'        assert(m::Inflate(z, {L}, true, false).out == {rs});',
              f'        assert(crate::limits::SEGMENT_BYTES_MAX >= {len(z)}) by (compute);',
              '    }', f'    let ghost raw = {rs};', f'    let mut output = [0xa5u8; {L}];',
              f'    check_at(&wire, &mut output, {execstatus}, Ghost(raw));', '}']
# Header-only failures and stored truncation do not require a decoding trace.
for name,status in [('zlib/cut-mid-stored','TruncatedZlib'),('deflate/btype-3','InvalidBlockType'),('deflate/hlit-287','InvalidCodeLengths'),('deflate/hdist-31','InvalidCodeLengths')]:
    z=wire(name); zs=seq(z)
    lines += [f'/// {name}: authored first error with an empty output prefix, R=4.',f'fn {name.replace("/","_").replace("-","_")}() {{',
              f'    let wire = [{", ".join(hex(x)+( "u8" if i==0 else "") for i,x in enumerate(z))}];', '    proof {',
              f'        assert(m::Inflate({zs}, 4, true, false).status == m::InflateStatus::Error(m::InflateFault::{status})) by (compute);',
              f'        assert(m::Inflate({zs}, 4, true, false).out == Seq::<u8>::empty()) by (compute);',
              f'        assert(crate::limits::SEGMENT_BYTES_MAX >= {len(z)}) by (compute);', '    }',
              '    let mut output = [0xa5u8; 4];',f'    check_at(&wire, &mut output, Status::Err(E::{status}), Ghost(Seq::<u8>::empty()));','}']
lines += ['proof fn invalid_fcheck(z: Seq<u8>, limit: nat)',
          '    requires z.len() >= 2, (256*z[0] as nat+z[1] as nat)%31 != 0,',
          '    ensures m::Inflate(z,limit,true,false).status == m::InflateStatus::Error(m::InflateFault::InvalidZlibHeader),',
          '        m::Inflate(z,limit,true,false).out == Seq::<u8>::empty(),', '{}']
name='zlib/fcheck'; z=wire(name)
lines += [f'fn fcheck_bytes() -> (wire: [u8;{len(z)}])',
          '    ensures wire@[0] == 0x78, wire@[1] == 0x9d,',
          f'{{ [{", ".join(hex(x)+( "u8" if i==0 else "") for i,x in enumerate(z))}] }}',
          f'/// {name}: independently authored FCHECK failure before any block, R=4.', '#[verifier::spinoff_prover]', 'fn zlib_fcheck() {',
          '    hide(m::Inflate);', '    let wire = fcheck_bytes();',
          '    proof { invalid_fcheck(wire@,4);',f'        assert(crate::limits::SEGMENT_BYTES_MAX >= {len(z)}) by (compute);', '    }',
          '    let ghost raw = Seq::<u8>::empty(); let mut output=[0xa5u8;4]; check_at(&wire,&mut output,Status::Err(E::InvalidZlibHeader),Ghost(raw));','}']
name = 'deflate/empty-stored-then-stored'
z = wire(name); zs = seq(z); rs = seq([0,65,0,66])
lines += [f'/// {name}: authored empty block followed by raw [0,65,0,66], R=4.', 'fn empty_stored_then_stored() {',
          f'    let wire = [{", ".join(hex(x)+( "u8" if i==0 else "") for i,x in enumerate(z))}];', '    proof {',
          f'        assert(m::Inflate({zs},4,true,false).status == m::InflateStatus::Done) by (compute);',
          f'        assert(m::Inflate({zs},4,true,false).out == {rs}) by (compute);',
          f'        assert(crate::limits::SEGMENT_BYTES_MAX >= {len(z)}) by (compute);', '    }',
          f'    let ghost raw = {rs}; let mut output = [0xa5u8;4]; check_at(&wire,&mut output,Status::Done,Ghost(raw));', '}']
lines += ['} // verus!', '']
(ROOT/'src/witness_cases.rs').write_text('\n'.join(lines))
print(f'Wrote {len(CASES)+6} authored witnesses; no oracle consulted')
