#!/usr/bin/env python3
"""M1b differential check: png_verus against png_oracle.py (Strict) and policy_oracle.py (RecommendedBeta)
on every probe input of the policy draft.

Inputs (de-duplicated by bytes, first name wins):
  - the non-padded records of the three vector files (spec-frozen, limits-draft, policy-draft);
  - every record of policy-draft/probes/results.json (vectors, probes, witnesses; inputs above 4 KiB
    regenerated by validate.resolve and checked by SHA-256);
  - the held-out sets A and B (probes/heldout_def.py);
  - the ICC probes of probes/icc_probes.py (EXTRA).
Per input it compares: Strict still (error name, or width, height and RGBA8 SHA-256), Strict still16
(exact RGBA16), Strict frames (constructor error, or canvas size, num_plays, every frame's rect, delay,
dispose, blend and canvas SHA-256, and the end), Strict icc (null, length and SHA-256, or error),
RecommendedBeta still (plus recovered) and RecommendedBeta frames (plus each frame's recovered).

Input bytes are written only to a scratch directory (argument --work, default under /tmp, regenerated on
every run); they are never written to the repository (PNG-Q16). The report (--out) holds names and verdicts.

Usage: python3 -I probe_diff.py --runner PATH [--work DIR] [--out FILE] [--timeout S] [--only SUBSTR]
"""
import argparse
import hashlib
import json
import signal
import subprocess
import sys
from pathlib import Path

PNG = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PNG / 'policy-draft'))
sys.path.insert(0, str(PNG / 'policy-draft' / 'probes'))
sys.path.insert(0, str(PNG / 'spec-frozen'))
import png_oracle as O  # noqa: E402  (spec-frozen; byte-identical to spec-draft's copy)
import policy_oracle as PO  # noqa: E402
import validate as V  # noqa: E402
import heldout_def as HD  # noqa: E402


def sha(b):
    return hashlib.sha256(b).hexdigest()


def collect(only=None):
    seen = {}

    def add(name, b):
        if only and only not in name:
            return
        seen.setdefault(bytes(b), name)

    for v in V.VEC:
        if 'pad_to' not in v:
            add('vec:' + v['name'], bytes.fromhex(v['input_hex']))
    for r in V.RESULTS:
        add(r['name'], V.resolve(r))
    for which in ('A', 'B'):
        for n, b, _ in HD.heldout(which):
            add(n, b)
    import icc_probes as IP
    for n, b, _ in IP.EXTRA:
        add('icc:' + n, b)
    return [(n, b) for b, n in seen.items()]


class Timeout(Exception):
    pass


def _alarm(*_):
    raise Timeout


def still_rec(r, rec_key=False):
    if 'error' in r:
        return {'error': r['error']}
    out = {'width': r['width'], 'height': r['height'], 'sha': sha(r['rgba'])}
    if rec_key:
        out['recovered'] = r['recovered']
    return out


def frames_rec(r, rec_key=False):
    if 'error' in r:
        return {'error': r['error']}
    fs = []
    for f in r['frames']:
        g = {'rect': list(f['rect']), 'delay': list(f['delay']) if f['delay'] is not None else None,
             'dispose': f['dispose'], 'blend': f['blend'], 'sha': sha(f['rgba'])}
        if rec_key:
            g['recovered'] = f['recovered']
        fs.append(g)
    return {'width': r['width'], 'height': r['height'], 'num_plays': r['num_plays'], 'frames': fs,
            'end': r['end'] if r['end'] == 'iend' else {'error': r['end']['error']}}


def oracle(b):
    out = {}
    out['still'] = still_rec(O.decode_still(b))
    s16 = O.decode_still16(b)
    out['still16'] = s16 if 'error' in s16 else {
        'width': s16['width'], 'height': s16['height'],
        'sha': sha(b''.join(v.to_bytes(2, 'big') for v in s16['rgba16']))}
    out['frames'] = frames_rec(O.decode_frames(b))
    ic = O.icc_profile(b)
    out['icc'] = ic if 'error' in ic else ({'icc': None} if ic['icc'] is None else
                                          {'icc_len': len(ic['icc']), 'icc_sha256': sha(ic['icc'])})
    out['rb_still'] = still_rec(PO.decode_still(b, PO.RECOMMENDED_BETA), True)
    out['rb_frames'] = frames_rec(PO.decode_frames(b, PO.RECOMMENDED_BETA), True)
    return out


KEYS = ('still', 'still16', 'frames', 'icc', 'rb_still', 'rb_frames')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runner', required=True)
    ap.add_argument('--work', default='/tmp/claude-0/png-verus-probe-inputs')
    ap.add_argument('--out')
    ap.add_argument('--timeout', type=int, default=600, help='seconds per input for the Python oracles')
    ap.add_argument('--only')
    a = ap.parse_args()
    items = collect(a.only)
    work = Path(a.work)
    work.mkdir(parents=True, exist_ok=True)
    paths = []
    for i, (n, b) in enumerate(items):
        p = work / f'{i:05d}.png'
        p.write_bytes(b)
        paths.append(str(p))
    proc = subprocess.run([a.runner], input='\n'.join(paths) + '\n', capture_output=True, text=True, timeout=3600)
    if proc.returncode != 0:
        sys.exit(f'runner failed: {proc.stderr[-2000:]}')
    rust = [json.loads(line) for line in proc.stdout.splitlines()]
    assert len(rust) == len(items), (len(rust), len(items))
    signal.signal(signal.SIGALRM, _alarm)
    stats = {k: [0, 0] for k in KEYS}
    diffs, timeouts = [], []
    accepted = {'still': 0, 'frames': 0, 'rb_still': 0}
    for (n, b), r in zip(items, rust):
        signal.alarm(a.timeout)
        try:
            o = oracle(b)
        except Timeout:
            timeouts.append(n)
            continue
        finally:
            signal.alarm(0)
        for k in KEYS:
            ok = o[k] == r[k]
            stats[k][0 if ok else 1] += 1
            if not ok:
                diffs.append({'name': n, 'entry': k, 'oracle': o[k], 'png_verus': r[k]})
        for k in accepted:
            if 'error' not in o[k]:
                accepted[k] += 1
    print(f'{len(items)} distinct inputs; oracle timeouts: {len(timeouts)} {timeouts}')
    for k in KEYS:
        print(f'  {k:10s} agree {stats[k][0]:5d}  differ {stats[k][1]}')
    print(f'  oracle-accepted inputs: Strict still {accepted["still"]}, Strict frames {accepted["frames"]}, '
          f'RecommendedBeta still {accepted["rb_still"]}')
    for d in diffs[:40]:
        print('DIFF', json.dumps(d)[:600])
    if a.out:
        Path(a.out).write_text(json.dumps({'inputs': len(items), 'timeouts': timeouts, 'stats': stats,
                                           'accepted': accepted, 'diffs': diffs}, indent=1))
    sys.exit(1 if diffs or timeouts else 0)


if __name__ == '__main__':
    main()
